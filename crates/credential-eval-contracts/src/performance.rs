//! Performance measurement documents (ADR 0002).
//!
//! Two measurement kinds that are not detection outcomes:
//!
//! * **latency**: alternating A/B batches of an external-process scanner on
//!   generated synthetic workloads, with an A/A control. The result is a
//!   direction (`faster`, `slower`, `indistinguishable`), never a budget.
//! * **allocation**: allocation request counts of in-process scanner builds
//!   on the same workloads. Counters hold request counts and sizes only.
//!
//! Both are recorded in a [`PerformanceArtifact`], a document kind of its own.
//! It is not part of the four frozen v1 documents and does not change them
//! (`docs/decisions/0002-performance-measurement-kinds.md`). Like the run
//! artifact it carries no matched values, no raw scanner output and no
//! generated input text: counts, sizes, timings, digests and identities only.

