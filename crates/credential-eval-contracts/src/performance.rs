/// Configuration of a latency run. Its canonical digest is the run's
/// `config_hash`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct PerformanceConfig {
    /// Document tag: `credential-eval/performance-config/v1`.
    pub schema: PerformanceConfigSchema,
    /// The build every direction is relative to (arm A and its A/A control).
    pub baseline: PerfSubject,
    /// The build under test (arm B).
    pub candidate: PerfSubject,
    /// Workloads, in measurement order.
    pub workloads: Vec<WorkloadSpec>,
    /// Shapes to measure each workload in. Sorted, unique.
    pub shapes: Vec<ScanShape>,
    /// Chunk size in bytes; used by the `chunked` shape.
    pub chunk_bytes: u32,
    /// Rounds of alternating batches (at least 3).
    pub rounds: u32,
    /// Invocations per batch. A sample is the batch time per invocation.
    pub batch_invocations: u32,
    /// Untimed invocations per arm and workload before measuring.
    pub warmup_invocations: u32,
    /// Explicit bounds.
    pub limits: PerfLimits,
    /// Toolchain the subjects were built with. Sorted by name.
    pub toolchain: Vec<ToolchainEntry>,
}

impl PerformanceConfig {
    /// Canonical digest of this configuration.
    pub fn config_hash(&self) -> Sha256Digest {
        sha256_canonical(self)
    }

    /// Check every bound. A refused configuration never runs.
    pub fn validate(&self) -> Result<(), String> {
        use bounds::*;
        if self.baseline.id == self.candidate.id {
            return Err("baseline and candidate need distinct ids".into());
        }
        for subject in [&self.baseline, &self.candidate] {
            if subject.program.is_empty() {
                return Err(format!("{}: program is empty", subject.id));
            }
            if subject.args.len() > MAX_ARGS {
                return Err(format!("{}: more than {MAX_ARGS} arguments", subject.id));
            }
            if subject.ok_exit_codes.is_empty() || subject.ok_exit_codes.len() > 16 {
                return Err(format!(
                    "{}: ok_exit_codes must hold 1..=16 codes",
                    subject.id
                ));
            }
            let slots = subject
                .args
                .iter()
                .filter(|a| a.as_str() == "{input}")
                .count();
            let expected = usize::from(subject.delivery == InputDelivery::File);
            if slots != expected {
                return Err(format!(
                    "{}: delivery {:?} needs exactly {expected} `{{input}}` argument, found {slots}",
                    subject.id, subject.delivery
                ));
            }
        }
        if self.workloads.is_empty() || self.workloads.len() > MAX_WORKLOADS {
            return Err(format!("workloads must number 1..={MAX_WORKLOADS}"));
        }
        let mut seen = std::collections::BTreeSet::new();
        for workload in &self.workloads {
            if workload.units == 0 {
                return Err(format!("{:?}: units must be positive", workload.id));
            }
            if !seen.insert(workload.id) {
                return Err(format!("{:?}: duplicate workload", workload.id));
            }
        }
        if self.shapes.is_empty() || self.shapes.windows(2).any(|w| w[0] >= w[1]) {
            return Err("shapes must be non-empty, sorted and unique".into());
        }
        if self.shapes.contains(&ScanShape::Chunked) && !CHUNK_BYTES.contains(&self.chunk_bytes) {
            return Err(format!("chunk_bytes must be within {CHUNK_BYTES:?}"));
        }
        if !(MIN_ROUNDS..=MAX_ROUNDS).contains(&self.rounds) {
            return Err(format!("rounds must be within {MIN_ROUNDS}..={MAX_ROUNDS}"));
        }
        if !(1..=MAX_BATCH).contains(&self.batch_invocations) {
            return Err(format!("batch_invocations must be within 1..={MAX_BATCH}"));
        }
        if self.warmup_invocations > MAX_WARMUP {
            return Err(format!("warmup_invocations must be at most {MAX_WARMUP}"));
        }
        let limits = &self.limits;
        if !(1..=MAX_TIMEOUT_MS).contains(&limits.timeout_ms)
            || !(1..=MAX_INPUT_BYTES).contains(&limits.max_input_bytes)
            || !(1..=MAX_CAPTURE_BYTES).contains(&limits.max_response_bytes)
            || limits.max_diagnostic_bytes > MAX_CAPTURE_BYTES
        {
            return Err("limits are outside the engine's bounds".into());
        }
        if self.toolchain.windows(2).any(|w| w[0].name >= w[1].name) {
            return Err("toolchain must be sorted by name, without duplicates".into());
        }
        Ok(())
    }
}

/// Which measurement kind an artifact records.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize, JsonSchema,
)]
#[serde(rename_all = "kebab-case")]
pub enum MeasurementKind {
    /// Latency of an external-process scanner.
    Latency,
    /// Allocation requests of in-process scanner builds.
    Allocation,
    /// Executed instructions of an external-process scanner, counted under
    /// `valgrind --tool=callgrind`: a deterministic proxy for scan cost.
    /// Added in a minor revision (ADR 0002).
    Instructions,
}

/// Identity of one subject (scanner build) in a run.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct SubjectIdentity {
    /// Subject id.
    pub id: ScannerId,
    /// Version label.
    pub version: ReleaseTag,
    /// Source revision, when built from a Git commit.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub revision: Option<GitRevision>,
    /// SHA-256 of the executable, for external-process subjects.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub executable_sha256: Option<Sha256Digest>,
    /// Digest of how the executable is invoked: arguments, input delivery and
    /// the exit codes that count as a scan (the subject's activation and
    /// options; never the executable path). Recorded from revision v1.1 of the
    /// artifact so a subject's measurement can be matched without the pair's
    /// whole `config_hash` (ADR 0010). Absent in older artifacts, whose
    /// subjects are then only reusable as part of their unchanged pair.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub invocation_digest: Option<Sha256Digest>,
    /// The arm this subject measured in a pairwise run. Absent for
    /// allocation, where the results name their subjects.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub role: Option<SubjectRole>,
}

/// The arm of a pairwise run a subject occupied.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize, JsonSchema,
)]
#[serde(rename_all = "kebab-case")]
pub enum SubjectRole {
    /// The build every direction is relative to (arm A and its A/A control).
    Baseline,
    /// The build under test (arm B).
    Candidate,
}

impl PerfSubject {
    /// Digest of the subject's invocation semantics: arguments, delivery and
    /// scan-success exit codes. Not the program path, which is where the
    /// executable lives, not what it is (its digest identifies it).
    pub fn invocation_digest(&self) -> Sha256Digest {
        sha256_canonical(&serde_json::json!({
            "args": self.args,
            "delivery": self.delivery,
            "ok_exit_codes": self.ok_exit_codes,
        }))
    }
}

