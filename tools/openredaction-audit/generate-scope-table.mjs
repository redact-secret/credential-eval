// Regenerates crates/credential-eval-contracts/src/scope_table_openredaction.rs
// from dispositions.json (ADR 0016). A test fails when the two differ.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const doc = JSON.parse(readFileSync(join(here, "dispositions.json"), "utf8"));
const scope = {
  credential: "Credential",
  "identifier-of-credential": "IdentifierOfCredential",
  session: "Session",
  ambiguous: "Ambiguous",
  "resource-identifier": "ResourceIdentifier",
  pii: "Pii",
  "pii-or-identifier": "PiiOrIdentifier",
};
const status = { mapped: "Mapped", unresolved: "Unresolved", "not-credential": "NotCredential" };
const esc = (s) => JSON.stringify(s);
const rows = doc.types
  .map((t) => {
    if (!scope[t.scope] || !status[t.status]) throw new Error(`unknown scope/status for ${t.type}`);
    return `    ScopeEntry { label: ${esc(t.type)}, scope: Scope::${scope[t.scope]}, status: DispositionStatus::${status[t.status]}, reason: ${esc(t.reason)} },`;
  })
  .join("\n");
const out = `//! Generated by tools/openredaction-audit/generate-scope-table.mjs from
//! tools/openredaction-audit/dispositions.json. Do not edit by hand (ADR 0016).

use crate::scope::{DispositionStatus, Scope, ScopeEntry};

pub const PACKAGE: &str = ${esc(doc.package)};
pub const VERSION: &str = ${esc(doc.version)};
pub const INTEGRITY: &str = ${esc(doc.integrity)};

/// One entry per reviewed native type, sorted by label.
pub const ENTRIES: &[ScopeEntry] = &[
${rows}
];
`;
writeFileSync(join(here, "../../crates/credential-eval-contracts/src/scope_table_openredaction.rs"), out);
