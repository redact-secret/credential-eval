#!/usr/bin/env python3
"""Feasibility of instruction counts as a deterministic timing proxy (issue #26).

For each workload and each pinned scanner build, run the scanner under
`valgrind --tool=callgrind` REPEATS times on the same input and record the
total instruction count (`Collected`). Reports, per cell:

* the run-to-run spread of one build (the question: is it zero or tiny?),
* the baseline->candidate instruction ratio after subtracting the cost of an
  empty-input run (process startup), and a direction when the ratio clears the
  measured spread,
* identical-build control: the same executable run as both arms must report no
  direction (no false direction).

Inputs are synthetic (generated by credential-eval-perf's `workload` example)
and are never printed. Usage:
    callgrind-feasibility.py <baseline-bin> <candidate-bin> <workload-dir> <out.json>
"""
import json
import re
import subprocess
import sys
from pathlib import Path

REPEATS = 3
COLLECTED = re.compile(r"Collected\s*:\s*(\d+)")


def instructions(binary: str, input_path: str | None) -> int:
    stdin = open(input_path, "rb") if input_path else subprocess.DEVNULL
    try:
        proc = subprocess.run(
            ["valgrind", "--tool=callgrind", "--callgrind-out-file=/dev/null", binary],
            stdin=stdin, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True,
            timeout=600,
        )
    finally:
        if input_path:
            stdin.close()
    match = COLLECTED.search(proc.stderr)
    if not match:
        raise SystemExit("no instruction count in valgrind output")
    return int(match.group(1))


def measure(binary: str, path: str | None) -> list[int]:
    return [instructions(binary, path) for _ in range(REPEATS)]


def main() -> None:
    baseline, candidate, workloads, out = sys.argv[1:5]
    cells = []
    startup = {b: measure(b, None) for b in {baseline, candidate}}
    for path in sorted(Path(workloads).glob("*.txt")):
        name = path.stem
        row = {"workload": name}
        for label, binary in (("baseline", baseline), ("candidate", candidate)):
            counts = measure(binary, str(path))
            row[label] = {
                "counts": counts,
                "spread": max(counts) - min(counts),
                "net": min(counts) - min(startup[binary]),
            }
        # Control: the baseline executable against itself.
        control = measure(baseline, str(path))
        row["control_spread_vs_baseline"] = abs(min(control) - min(row["baseline"]["counts"]))
        base_net = max(row["baseline"]["net"], 1)
        row["ratio"] = row["candidate"]["net"] / base_net
        noise = max(row["baseline"]["spread"], row["candidate"]["spread"],
                    row["control_spread_vs_baseline"]) / base_net
        row["noise"] = noise
        floor = 0.001  # instruction counts are exact; 0.1% is already a real change
        band = max(noise, floor)
        row["direction"] = ("faster" if row["ratio"] < 1 - band
                            else "slower" if row["ratio"] > 1 + band
                            else "indistinguishable")
        cells.append(row)
        print(f'{name:30} ratio {row["ratio"]:.4f} noise {noise:.6f} '
              f'spread {row["baseline"]["spread"]}/{row["candidate"]["spread"]} {row["direction"]}')
    Path(out).write_text(json.dumps({"repeats": REPEATS, "cells": cells}, indent=1) + "\n")


if __name__ == "__main__":
    main()
